import { chromium } from '@playwright/test';
const S = process.argv[2];
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
page.on('pageerror', e => console.log('pageerror', e.message));
await page.goto('http://127.0.0.1:8080/#skills');
await page.waitForTimeout(2600);
await page.screenshot({ path: `${S}/p8-board.png` });
await page.getByRole('button', { name: 'Python', exact: true }).click();
await page.mouse.move(5, 5);
await page.waitForTimeout(400);
await page.screenshot({ path: `${S}/p8-python.png` });
console.log('status:', await page.locator('.skills-status').textContent());
await page.getByRole('button', { name: 'TideCast', exact: true }).hover();
await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/p8-hover-tidecast.png` });
await browser.close();
