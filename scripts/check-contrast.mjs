// Computes WCAG 2.2 contrast for every text/UI token pair in both themes,
// including translucent surfaces composited over the page background and the
// accent gradient endpoints. Writes reports/contrast.md; exits 1 on a failure.
// Usage: node scripts/check-contrast.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(join(root, 'css/tokens.css'), 'utf8');

function block(selector) {
  const i = css.indexOf(selector);
  const start = css.indexOf('{', i) + 1;
  let depth = 1, j = start;
  while (depth && j < css.length) { if (css[j] === '{') depth++; if (css[j] === '}') depth--; j++; }
  const vars = {};
  for (const [, k, v] of css.slice(start, j - 1).matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[k] = v.trim();
  return vars;
}
const dark = block(':root {');
const light = { ...dark, ...block(":root[data-theme='light'] {") };

function parse(c) {
  c = c.trim();
  let m = /^#([0-9a-f]{6})$/i.exec(c);
  if (m) return { r: parseInt(m[1].slice(0, 2), 16), g: parseInt(m[1].slice(2, 4), 16), b: parseInt(m[1].slice(4, 6), 16), a: 1 };
  m = /^rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*(?:\/\s*([\d.]+))?\s*\)$/.exec(c);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] };
  throw new Error(`Unparsed colour ${c}`);
}
const over = (fg, bg) => ({ r: fg.r * fg.a + bg.r * (1 - fg.a), g: fg.g * fg.a + bg.g * (1 - fg.a), b: fg.b * fg.a + bg.b * (1 - fg.a), a: 1 });
const lum = ({ r, g, b }) => {
  const f = (v) => { v /= 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

// [foreground, background(s), requirement, usage]
const PAIRS = [
  ['ink', ['bg'], 4.5, 'body text, headings'],
  ['ink-soft', ['bg'], 4.5, 'secondary text, bullets'],
  ['muted', ['bg'], 4.5, 'meta text, captions'],
  ['copper', ['bg'], 4.5, 'kickers (12px), small labels'],
  ['copper-strong', ['bg'], 4.5, 'link hover, status text'],
  ['ink', ['surface@bg'], 4.5, 'text on translucent cards'],
  ['ink-soft', ['surface@bg'], 4.5, 'bullets on cards'],
  ['muted', ['surface@bg'], 4.5, 'meta on cards'],
  ['copper', ['surface@bg'], 4.5, 'kickers on cards'],
  ['ink', ['surface-solid'], 4.5, 'buttons, chapter labels'],
  ['ink-soft', ['surface-solid'], 4.5, 'segmented controls'],
  ['on-copper', ['copper'], 4.5, 'primary button label'],
  ['on-copper', ['copper-strong'], 4.5, 'primary button hover'],
  ['ink-soft', ['header-glass@ink', 'header-glass@bg', 'header-glass@copper'], 4.5, 'header nav over the worst content behind the glass'],
  ['focus-inner', ['bg', 'surface-solid'], 3, 'focus ring against the page (non-text, 3:1)'],
  ['focus-inner', ['focus-outer'], 3, 'focus ring against its halo (the ring sits 2px outside every control)'],
  ['focus-outer', ['copper'], 3, 'halo separating the ring from a copper button'],
  ['border-strong@bg', ['bg'], 1.5, 'decorative borders (informational only; controls have text labels)'],
  ['muted', ['bg'], 3, 'chapter dot outline (non-text, 3:1)'],
  ['accent-a', ['bg'], 0, 'accent gradient start (ornamental only)'],
  ['accent-b', ['bg'], 0, 'accent gradient end (ornamental only)'],
];

function resolve(theme, token) {
  if (token.includes('@')) {
    const [fg, bg] = token.split('@');
    return over(parse(theme[fg]), resolve(theme, bg));
  }
  return parse(theme[token]);
}

const lines = ['# Contrast report', '', `Generated by \`scripts/check-contrast.mjs\` from css/tokens.css on ${new Date().toISOString().slice(0, 10)}. WCAG 2.2: 4.5:1 normal text, 3:1 large text and non-text UI. "a@b" means token a composited over b.`, ''];
let failures = 0;
for (const [name, theme] of [['Dark', dark], ['Light', light]]) {
  lines.push(`## ${name} theme`, '', '| Foreground | Background | Ratio | Needs | Result | Use |', '|---|---|---|---|---|---|');
  for (const [fg, bgs, need, use] of PAIRS) {
    for (const bg of bgs) {
      const r = ratio(resolve(theme, fg), resolve(theme, bg));
      const ok = need === 0 || r >= need;
      if (!ok) failures++;
      lines.push(`| ${fg} | ${bg} | ${r.toFixed(2)}:1 | ${need ? need + ':1' : 'decorative'} | ${need === 0 ? (r >= 3 ? 'ornament (≥3)' : 'ornament only') : ok ? 'pass' : '**FAIL**'} | ${use} |`);
    }
  }
  lines.push('');
}
lines.push('Accent red is used only for ornament (LED glow, gradient hairlines); it never carries text or required UI state.', '');
mkdirSync(join(root, 'reports'), { recursive: true });
writeFileSync(join(root, 'reports/contrast.md'), lines.join('\n'));
console.log(failures ? `✗ ${failures} contrast failure(s); see reports/contrast.md` : '✓ all required contrast pairs pass (reports/contrast.md)');
process.exit(failures ? 1 : 0);
